"use client";

import * as React from "react";
import Link from "next/link";
import { useSearchParams } from "next/navigation";
import {
  ShieldCheck,
  CheckCircle2,
  ArrowRight,
} from "lucide-react";
import { Button, Input, Card, useToast } from "@/components/ui";
import { BrandLogo } from "@/components/brand/logo";
import { CAREER_AVSAR_BRAND } from "@/lib/brand/config";

function SchoolActivateForm() {
  const searchParams = useSearchParams();
  const { push } = useToast();

  const tokenParam = searchParams.get("token") || "";
  const schoolParam = searchParams.get("school") || "Your Institution";
  const [token, setToken] = React.useState(tokenParam);
  const [password, setPassword] = React.useState("");
  const [confirmPassword, setConfirmPassword] = React.useState("");
  const [error, setError] = React.useState<string | null>(null);
  const [success, setSuccess] = React.useState(false);
  const [busy, setBusy] = React.useState(false);

  React.useEffect(() => {
    if (tokenParam) setToken(tokenParam);
  }, [tokenParam]);

  async function handleActivate(e: React.FormEvent) {
    e.preventDefault();
    setError(null);

    if (!token.trim()) {
      return setError("Please provide your single-use activation invitation token.");
    }

    if (password.length < 8) {
      return setError("Password must be at least 8 characters in length.");
    }

    if (password !== confirmPassword) {
      return setError("Passwords do not match. Please re-enter.");
    }

    setBusy(true);

    // Call activation API or simulate completion
    setTimeout(() => {
      setBusy(false);
      setSuccess(true);
      push({
        tone: "success",
        title: "Account Activated",
        message: "Your institutional portal account is now active. Please sign in.",
      });
    }, 800);
  }

  return (
    <div className="min-h-screen bg-[#F6F8FC] flex flex-col justify-center py-12 sm:px-6 lg:px-8">
      <div className="sm:mx-auto sm:w-full sm:max-w-md">
        <div className="text-center flex flex-col items-center">
          <BrandLogo size="lg" showTagline={true} />
          <h1 className="mt-4 font-serif text-3xl font-bold tracking-tight text-[#14264D]">
            Activate School Portal
          </h1>
          <p className="mt-1 text-xs font-semibold uppercase tracking-wider text-[#F28B19]">
            {CAREER_AVSAR_BRAND.tagline}
          </p>
          <p className="mt-2 text-xs text-[#687487]">
            Set up your institutional recruitment password for {schoolParam}
          </p>
        </div>

        <Card className="mt-8 p-6 sm:p-8 bg-white border border-slate-200 shadow-sm rounded-2xl">
          {success ? (
            <div className="text-center py-4 space-y-4">
              <span className="mx-auto flex size-12 items-center justify-center rounded-full bg-green-50 text-success">
                <CheckCircle2 className="size-8" />
              </span>
              <h2 className="font-serif text-xl font-bold text-[#14264D]">
                Account Successfully Activated
              </h2>
              <p className="text-xs text-[#687487] max-w-sm mx-auto">
                Your password has been configured securely. You may now sign in to review shared candidate dossiers and manage vacancy requests.
              </p>
              <div className="pt-2">
                <Button asChildLink href="/school/login" size="lg" className="bg-[#1266C5] text-white font-bold w-full">
                  <span>Proceed to School Sign In</span>
                  <ArrowRight className="size-4 ml-1" />
                </Button>
              </div>
            </div>
          ) : (
            <form onSubmit={handleActivate} className="space-y-4">
              <div className="rounded-xl border border-blue-200 bg-blue-50/70 p-3 text-xs text-[#14264D]">
                <div className="flex items-center gap-1.5 font-semibold">
                  <ShieldCheck className="size-4 text-[#1266C5]" />
                  <span>Secure Single-Use Activation</span>
                </div>
                <p className="mt-1 text-[11px] text-slate-600">
                  This activation link was generated by the Career Avsar administrator and is valid for 48 hours.
                </p>
              </div>

              <Input
                label="Invitation Activation Token"
                type="text"
                required
                placeholder="e.g. act_7f9b8c2..."
                value={token}
                onChange={(e) => setToken(e.target.value)}
              />

              <Input
                label="Create Password"
                type="password"
                required
                placeholder="Minimum 8 characters"
                value={password}
                onChange={(e) => setPassword(e.target.value)}
              />

              <Input
                label="Confirm Password"
                type="password"
                required
                placeholder="Re-enter your password"
                value={confirmPassword}
                onChange={(e) => setConfirmPassword(e.target.value)}
              />

              {error ? (
                <div role="alert" className="rounded-lg border border-red-200 bg-red-50 p-3 text-xs font-medium text-danger">
                  {error}
                </div>
              ) : null}

              <Button
                type="submit"
                fullWidth
                size="lg"
                disabled={busy}
                className="bg-[#1266C5] hover:bg-[#087FE8] text-white font-bold"
              >
                <span>{busy ? "Activating Account…" : "Complete Activation"}</span>
                <ArrowRight aria-hidden className="size-4 text-[#F28B19]" />
              </Button>
            </form>
          )}

          <div className="mt-6 border-t border-slate-100 pt-4 text-center text-xs text-[#687487]">
            <Link href="/school/login" className="font-semibold text-[#1266C5] hover:underline">
              Already activated? Sign In
            </Link>
          </div>
        </Card>
      </div>
    </div>
  );
}

export default function SchoolActivatePage() {
  return (
    <React.Suspense
      fallback={
        <div className="min-h-screen bg-[#F6F8FC] flex items-center justify-center font-serif text-[#14264D]">
          Loading Activation…
        </div>
      }
    >
      <SchoolActivateForm />
    </React.Suspense>
  );
}
